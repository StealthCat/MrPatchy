const assert=require('assert/strict');
module.exports=async function tlsUI(page,capture){
  let state=await (await page.request.get(new URL('/api/tls',page.url()).href)).json();
  const submitted=[];
  await page.route('**/api/tls',route=>route.fulfill({json:state}));
  await page.route('**/api/tls/*',route=>{
    const profile=route.request().url().split('/').pop(),body=route.request().postDataJSON();submitted.push({profile,body});
    const old=state.profiles[profile];
    state.profiles[profile]={...old,...body,ca_configured:!!body.ca||old.ca_configured,eab_configured:!!body.eab_key||old.eab_configured};
    for(const secret of ['certificate','private_key','ca','eab_key'])delete state.profiles[profile][secret];
    return route.fulfill({json:state});
  });
  await page.getByRole('button',{name:'Configure HTTPS →',exact:true}).click();
  await page.locator('#tls-profile').selectOption('external');
  assert.equal(await page.locator('#tls-form [name=enabled]').isChecked(),false);
  await page.locator('#tls-form [name=enabled]').check();
  await page.locator('#tls-form [name=domain]').fill('patchy.example.test');
  assert.equal(await page.locator('#tls-form [name=mode]').inputValue(),'acme');
  assert.equal(await page.locator('#tls-form [name=acme_url]').inputValue(),'https://acme-v02.api.letsencrypt.org/directory');
  await page.locator('#tls-form [name=email]').fill('ops@example.test');
  await page.locator('#tls-form [name=https_port]').fill('9443');
  await page.locator('#tls-form [name=eab_id]').fill('fixture-account');
  await page.locator('#tls-form [name=eab_key]').fill('YWJj');
  await page.getByRole('button',{name:'Validate & apply this profile',exact:true}).click();
  await page.locator('#modal-message').filter({hasText:'HTTPS profile applied'}).waitFor();
  assert.equal(submitted[0].profile,'external');assert.equal(submitted[0].body.https_port,9443);
  assert.equal(await page.locator('#tls-form [name=eab_key]').inputValue(),'');
  await page.locator('#tls-profile').selectOption('internal');
  assert.equal(await page.locator('#tls-form [name=domain]').inputValue(),'localhost');
  assert.equal(await page.locator('#tls-acme').isVisible(),false);
  await page.locator('#tls-form [name=mode]').selectOption('uploaded');
  assert.equal(await page.locator('#tls-upload').isVisible(),true);
  await page.locator('#tls-profile').selectOption('external');
  assert.equal(await page.locator('#tls-form [name=domain]').inputValue(),'patchy.example.test');
  await page.locator('#modal').evaluate(node=>node.scrollTop=0);
  await capture('https-profiles',false);
  await page.getByRole('button',{name:'Validate & apply this profile',exact:true}).click();
  await page.locator('#modal-message').filter({hasText:'HTTPS profile applied'}).waitFor();
  assert.equal(submitted[1].body.eab_key,'');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.locator('#modal').evaluate(x=>x.scrollWidth>x.clientWidth),false);
  await page.locator('#close-modal').click();await page.setViewportSize({width:1440,height:1000});
  await page.unroute('**/api/tls');await page.unroute('**/api/tls/*');
};
