const assert=require('assert/strict');
module.exports=async function schedulesUI(page,capture){
  await page.locator('[data-nav=schedules]').click();
  await page.getByRole('heading',{name:'Patching, on your calendar.'}).waitFor();
  await page.getByRole('button',{name:'+ Create schedule'}).click();
  const form=page.locator('#schedule-form');
  await form.locator('[name=name]').fill('Daily fleet care');
  await form.locator('[name=frequency]').selectOption('daily');
  await form.locator('[name=timezone]').fill('America/New_York');
  await form.locator('[name=start_time]').fill('02:00');
  await form.locator('[name=critical_enabled]').check();
  await form.locator('[name=critical_bypass]').check();
  await form.locator('[name=high_enabled]').check();
  await form.locator('[name=high_after]').fill('120');
  await form.locator('[name=enabled]').check();
  assert.equal(await form.evaluate(node=>node.checkValidity()),false);
  await form.locator('[name=approved]').check();
  await page.getByRole('button',{name:'Review schedule →'}).click();
  await page.getByRole('heading',{name:'Review unattended patching'}).waitFor();
  assert.match(await page.locator('#modal-body').innerText(),/outside maintenance windows allowed/);
  await page.getByRole('button',{name:'Approve & enable schedule'}).click();
  await page.locator('[data-pause-schedule]').waitFor();
  const result=await (await page.request.get(new URL('/api/schedules',page.url()).href)).json();
  assert.equal(result.schedules.length,1);
  const saved=result.schedules[0];assert.equal(saved.high.after_minutes,120);assert.equal(saved.critical.bypass_window,true);assert.equal(saved.all_hosts,true);
  const tomorrow=new Date();tomorrow.setDate(tomorrow.getDate()+1);
  const date=`${tomorrow.getFullYear()}-${String(tomorrow.getMonth()+1).padStart(2,'0')}-${String(tomorrow.getDate()).padStart(2,'0')}`;
  await page.locator('#calendar-date').fill(date);
  await page.locator('.calendar-event').first().waitFor();
  await page.locator('#toast').waitFor({state:'hidden'});
  await page.locator('#calendar-title').click();
  await capture('patch-calendar');
  await page.locator('#calendar-view').selectOption('day');
  await page.locator('.calendar-hour .calendar-event').first().waitFor();
  assert.ok(await page.locator('.calendar-hour').count()>=23);
  await capture('patch-hourly');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await capture('patch-hourly-mobile');
  await page.locator('#calendar-view').selectOption('month');
  await page.locator('.calendar-month').waitFor();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('[data-edit-schedule]').click();
  await page.locator('#schedule-form').waitFor();
  assert.equal(await page.locator('#schedule-form [name=critical_bypass]').isChecked(),true);
  assert.equal(await page.locator('#schedule-form [name=approved]').isChecked(),false);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.locator('#modal').evaluate(node=>node.scrollWidth>node.clientWidth),false);
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#modal').evaluate(node=>node.scrollTop=0);
  await capture('patch-schedule-editor',false);
  await page.locator('#close-modal').click();
  await page.locator('[data-pause-schedule]').click();
  await page.locator('.schedule-item .badge.paused').waitFor();
  assert.equal(await page.locator('[data-pause-schedule]').count(),0);
  await page.locator('[data-delete-schedule]').click();
  await page.getByRole('button',{name:'Delete schedule',exact:true}).click();
  await page.getByRole('heading',{name:'A predictable patching rhythm'}).waitFor();
};
