const assert=require('assert/strict');
module.exports=async function schedulesUI(page,capture){
  await page.locator('[data-nav=schedules]').click();
  await page.getByRole('heading',{name:'Patching, on your calendar.'}).waitFor();
  await page.getByRole('button',{name:'+ Create schedule'}).click();
  const form=page.locator('#schedule-form');
  await form.locator('[name=name]').fill('Daily fleet care');
  await form.locator('[name=frequency]').selectOption('daily');
  await form.locator('[name=timezone]').fill('America/New_York');
  await form.locator('[name=start_time]').fill('02:00');
  await form.locator('[name=critical_enabled]').check();
  await form.locator('[name=critical_bypass]').check();
  await form.locator('[name=high_enabled]').check();
  await form.locator('[name=high_after]').fill('120');
  await form.locator('[name=enabled]').check();
  assert.equal(await form.evaluate(node=>node.checkValidity()),false);
  await form.locator('[name=approved]').check();
  await page.getByRole('button',{name:'Review schedule →'}).click();
  await page.getByRole('heading',{name:'Review unattended patching'}).waitFor();
  assert.match(await page.locator('#modal-body').innerText(),/outside maintenance windows allowed/);
  await page.getByRole('button',{name:'Approve & enable schedule'}).click();
  await page.locator('[data-pause-schedule]').waitFor();
  const result=await (await page.request.get(new URL('/api/schedules',page.url()).href)).json();
  assert.equal(result.schedules.length,1);
  const saved=result.schedules[0];assert.equal(saved.high.after_minutes,120);assert.equal(saved.critical.bypass_window,true);assert.equal(saved.all_hosts,true);
  const tomorrow=new Date();tomorrow.setDate(tomorrow.getDate()+1);
  const date=`${tomorrow.getFullYear()}-${String(tomorrow.getMonth()+1).padStart(2,'0')}-${String(tomorrow.getDate()).padStart(2,'0')}`;
  await page.locator('#calendar-date').fill(date);
  await page.locator('.calendar-event').first().waitFor();
  await page.locator('#toast').waitFor({state:'hidden'});
  await page.locator('#calendar-title').click();
  await capture('patch-calendar');
  await page.locator('#calendar-view').selectOption('day');
  await page.locator('.calendar-hour .calendar-event').first().waitFor();
  assert.ok(await page.locator('.calendar-hour').count()>=23);
  await capture('patch-hourly');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await capture('patch-hourly-mobile');
  await page.locator('#calendar-view').selectOption('month');
  await page.locator('.calendar-month').waitFor();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  // #1540: month columns read Sat, Mon–Fri, Sun while each row stays one Monday–Sunday week.
  const at=(day,hour)=>new Date(`${day}T${hour}:00:00`).getTime()/1000;
  const weekendEvents=[['2026-02-28','Saturday care'],['2026-03-01','Sunday care']].map(([day,title])=>({start:at(day,'10'),end:at(day,'11'),title,trigger:'regular',servers:1,states:{},timezone:''}));
  await page.route('**/api/schedules/calendar?*',route=>route.fulfill({json:{events:weekendEvents}}));
  const checkWeekOrder=async()=>{
    await page.locator('#calendar-date').fill('2026-02-14');
    await page.locator('#calendar-title').filter({hasText:'February 2026'}).waitFor();
    await page.locator('.calendar-cell[data-weekday] [data-day="2026-03-01"]').waitFor();
    assert.deepEqual(await page.locator('.calendar-weekday').allInnerTexts(),['Sat','Mon','Tue','Wed','Thu','Fri','Sun']);
    const days=await page.locator('.calendar-day').evaluateAll(nodes=>nodes.map(node=>node.dataset.day));
    assert.equal(days.length,35);
    assert.deepEqual(days.slice(0,7),['2026-01-31','2026-01-26','2026-01-27','2026-01-28','2026-01-29','2026-01-30','2026-02-01']);
    assert.deepEqual(days.slice(28),['2026-02-28','2026-02-23','2026-02-24','2026-02-25','2026-02-26','2026-02-27','2026-03-01']);
    const saturday=page.locator('.calendar-cell').filter({has:page.locator('[data-day="2026-02-28"]')});
    const sunday=page.locator('.calendar-cell').filter({has:page.locator('[data-day="2026-03-01"]')});
    assert.match(await saturday.innerText(),/Saturday care/);assert.doesNotMatch(await saturday.innerText(),/Sunday care/);
    assert.match(await sunday.innerText(),/Sunday care/);assert.match(await sunday.getAttribute('class'),/outside/);
    assert.equal(await saturday.getAttribute('data-weekday'),'Saturday');
    assert.equal(await page.locator('[data-day="2026-02-28"]').getAttribute('aria-label'),'Hourly schedule for Saturday 2026-02-28');
    const monday=page.locator('.calendar-cell').filter({has:page.locator('[data-day="2026-02-23"]')});
    const [sat,mon,sun]=await Promise.all([saturday,monday,sunday].map(cell=>cell.boundingBox()));
    assert.ok(sat.x<mon.x&&mon.x<sun.x&&Math.abs(sat.y-sun.y)<2,'Saturday left, Sunday right in one row');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.locator('[data-day="2026-02-28"]').focus();await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(()=>document.activeElement.dataset.day),'2026-02-23');
  };
  await checkWeekOrder();
  await capture('patch-calendar-month-mobile');
  await page.setViewportSize({width:1440,height:1000});
  await checkWeekOrder();
  await capture('patch-calendar-month');
  await page.locator('[data-day="2026-02-28"]').press('Enter');
  await page.locator('#calendar-view').evaluate(node=>node.value==='day'||Promise.reject(new Error('not day view')));
  assert.equal(await page.locator('#calendar-date').inputValue(),'2026-02-28');
  await page.locator('.calendar-hour .calendar-event').filter({hasText:'Saturday care'}).waitFor();
  await page.locator('#calendar-next').click();
  assert.equal(await page.locator('#calendar-date').inputValue(),'2026-03-01');
  await page.locator('.calendar-hour .calendar-event').filter({hasText:'Sunday care'}).waitFor();
  await page.locator('#calendar-view').selectOption('month');
  await page.locator('#calendar-title').filter({hasText:'March 2026'}).waitFor();
  assert.deepEqual(await page.locator('.calendar-day').evaluateAll(nodes=>nodes.slice(0,7).map(node=>node.dataset.day)),['2026-02-28','2026-02-23','2026-02-24','2026-02-25','2026-02-26','2026-02-27','2026-03-01']);
  await page.locator('#calendar-prev').click();
  await page.locator('#calendar-title').filter({hasText:'February 2026'}).waitFor();
  await page.unroute('**/api/schedules/calendar?*');
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('[data-edit-schedule]').click();
  await page.locator('#schedule-form').waitFor();
  assert.equal(await page.locator('#schedule-form [name=critical_bypass]').isChecked(),true);
  assert.equal(await page.locator('#schedule-form [name=approved]').isChecked(),false);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.locator('#modal').evaluate(node=>node.scrollWidth>node.clientWidth),false);
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#modal').evaluate(node=>node.scrollTop=0);
  await capture('patch-schedule-editor',false);
  await page.locator('#close-modal').click();
  await page.locator('[data-pause-schedule]').click();
  await page.locator('.schedule-item .badge.paused').waitFor();
  assert.equal(await page.locator('[data-pause-schedule]').count(),0);
  await page.locator('[data-delete-schedule]').click();
  await page.getByRole('button',{name:'Delete schedule',exact:true}).click();
  await page.getByRole('heading',{name:'A predictable patching rhythm'}).waitFor();
};
