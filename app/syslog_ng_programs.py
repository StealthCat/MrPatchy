"""Pure syslog-ng command contract (roadmap F slice, #1570).

syslog-ng starts shell commands from its configuration. A ``program()``
source or destination runs a command for as long as syslog-ng runs (a source
is restarted when it exits; a destination receives every routed message),
``hook-commands()`` runs setup/startup commands when its driver starts and
teardown/shutdown commands when it stops, and an ``@module confgen`` generator
runs its ``exec()`` command when a source or destination uses it, to generate
configuration. They run as syslog-ng's user, which is root in the Debian,
Ubuntu and RHEL packages unless the command line passes ``--user``.

This module turns captured configuration text and captured include directory
listings into those commands: the exact string, the shell argv, the file and
line, and whether syslog-ng starts it. It performs no I/O, never runs
syslog-ng, a program or a shell, and never authorizes a response action.

The rules were observed by running the real syslog-ng 4.3.1 (Ubuntu 24.04
``syslog-ng-core 4.3.1-2build5``) as root on generated configurations with a
probe program that recorded its argv, its parent's command line and its uid:

- ``program("cmd")`` runs ``/bin/sh -c cmd``. ``hook-commands()`` and confgen
  ``exec()`` run ``sh -c -- cmd``. The shell, not syslog-ng, splits words.
- Only drivers that a ``log`` path references by name, or defines inline,
  start. A driver referenced by several paths starts once. Unreferenced
  definitions, their hooks and unused confgen generators do not run.
- Double-quoted strings decode ``\\t``, ``\\n``, ``\\r``, ``\\xNN``, ``\\\\`` and
  ``\\"``; other escapes keep the character. Single-quoted strings are literal.
  Two adjacent strings in ``program()`` are a syntax error.
- A backtick name inside a string expands an ``@define`` value seen earlier
  in configuration order. Any other name (a later definition, a built-in
  variable such as ``scl-root``, or the environment) is not resolved here.
- ``@include`` of a relative path searches ``/etc/syslog-ng`` and then
  ``/usr/share/syslog-ng/include``. A glob includes matching entries that do
  not start with ``.`` in sorted order; an unmatched glob is not an error. A
  missing non-glob include stops syslog-ng from starting. A directory include
  takes, in sorted order, only entries whose names consist of
  ``[A-Za-z0-9_.-]`` and do not start with ``.``.
- A ``log`` reference to an undefined source or destination, or a duplicate
  source/destination name, stops syslog-ng from starting, so nothing runs.

Fail-closed rules: an unobserved file or listing, invalid UTF-8, NUL bytes,
over-limit input, unterminated strings or braces, an unresolved backtick in a
running command, a referenced driver defined by a ``block`` (not expanded
here), a running confgen generator (its generated configuration is not
observed), ``allow-config-dups`` and ambiguous relative globs mark the result
incomplete. ``origin`` is always ``not_assessed``, ``authorizes_response`` is
always false and no result is a safety verdict.
"""
