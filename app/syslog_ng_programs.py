_WORD = re.compile(r'[A-Za-z0-9_.@:/*+\-]+')
_GLOB = re.compile(r'[*?\[]')
_DIR_ENTRY = re.compile(r'[A-Za-z0-9_.-]+')
_DEFINE = re.compile(r'@define[ \t]+([A-Za-z0-9_-]+)[ \t]+(.*)$')
_ESCAPES = {'t': '\t', 'n': '\n', 'r': '\r', 'a': '\a', 'b': '\b', 'f': '\f', 'v': '\v'}


class _Syntax(Exception):
    pass


class _Token:
    __slots__ = ('kind', 'value', 'path', 'line', 'unresolved')

    def __init__(self, kind: str, value: str, path: str, line: int, unresolved: tuple[str, ...] = ()):
        self.kind = kind
        self.value = value
        self.path = path
        self.line = line
        self.unresolved = unresolved


def _norm(name: str) -> str:
    return name.replace('_', '-').lower()


def decode_double(body: str) -> str:
    """Return the value syslog-ng's lexer builds from a double-quoted string body."""
    out = ''
    index = 0
    while index < len(body):
        char = body[index]
        if char != '\\' or index + 1 >= len(body):
            out += char
            index += 1
            continue
        nxt = body[index + 1]
        if nxt == 'x' and re.fullmatch(r'[0-9A-Fa-f]{2}', body[index + 2:index + 4]):
            out += chr(int(body[index + 2:index + 4], 16))
            index += 4
            continue
        out += _ESCAPES.get(nxt, nxt)
        index += 2
    return out


def _glob_match(pattern: str, name: str) -> bool:
    if name.startswith('.') and not pattern.startswith('.'):
        return False
    regex = ''
    index = 0
    while index < len(pattern):
        char = pattern[index]
        index += 1
        if char == '*':
            regex += '.*'
        elif char == '?':
            regex += '.'
        elif char == '[':
            end = pattern.find(']', index + 1 if index < len(pattern) and pattern[index] in '!^]' else index)
            if end < 0:
                regex += re.escape(char)
                continue
            body = pattern[index:end]
            index = end + 1
            if body[:1] in ('!', '^'):
                body = '^' + body[1:]
            regex += '[' + body.replace('\\', '\\\\') + ']'
        else:
            regex += re.escape(char)
    return re.fullmatch(regex, name, re.DOTALL) is not None


class _State:
    def __init__(self, files: Mapping[str, str | bytes | None], listings: Mapping[str, Iterable[str] | None],
                 include_path: tuple[str, ...]):
        self.files = files
        self.listings = {key.rstrip('/') or '/': value for key, value in listings.items()}
        self.include_path = include_path
        self.gaps: list[dict[str, Any]] = []
        self.read: list[dict[str, Any]] = []
        self.tokens: list[_Token] = []
        self.defines: dict[str, str] = {}
        self.confgen: list[dict[str, Any]] = []
        self.fatal: list[dict[str, Any]] = []
        self.notes: list[str] = []

    def gap(self, code: str, path: str | None, detail: str = '') -> None:
        if len(self.gaps) < MAX_GAPS:
            self.gaps.append({'code': code, 'path': path, 'detail': detail[:240], 'blocking': code in BLOCKING})
        elif self.gaps[-1]['code'] != 'gaps_truncated':
            self.gaps.append({'code': 'gaps_truncated', 'path': None, 'detail': 'Further gaps were not recorded.',
                              'blocking': True})

    def stop(self, code: str, path: str, line: int, detail: str) -> None:
        self.fatal.append({'code': code, 'path': path, 'line': line, 'detail': detail[:240]})

    def listing(self, directory: str) -> list[str] | None:
        entries = self.listings.get(directory.rstrip('/') or '/')
        return None if entries is None else sorted(set(entries))

    def has_file(self, path: str) -> bool:
        return self.files.get(path) is not None


def _expand_backticks(state: _State, value: str) -> tuple[str, tuple[str, ...]]:
    unresolved: list[str] = []

    def replace(match: re.Match[str]) -> str:
        name = match.group(1)
        if name in state.defines:
            return state.defines[name]
        unresolved.append(name)
        return match.group(0)

    return re.sub(r'`([^`]*)`', replace, value), tuple(unresolved)


def _pragma_value(text: str) -> str:
    text = text.strip()
    if len(text) >= 2 and text[0] == text[-1] and text[0] in '"\'':
        return decode_double(text[1:-1]) if text[0] == '"' else text[1:-1]
    return text.split('#', 1)[0].strip()


def _glob_paths(state: _State, pattern: str, source: str) -> list[str] | None:
    parts = pattern.strip('/').split('/')
    current = ['/']
    for index, part in enumerate(parts):
        nxt: list[str] = []
        for base in current:
            if not _GLOB.search(part):
                nxt.append(posixpath.join(base, part))
                continue
            entries = state.listing(base)
            if entries is None:
                parent, name = posixpath.split(base.rstrip('/'))
                parent_entries = state.listing(parent) if name else None
                if parent_entries is not None and name not in parent_entries:
                    continue
                state.gap('listing_not_observed', base, f'needed for include {pattern!r} in {source}')
                return None
            nxt.extend(posixpath.join(base, name) for name in entries if _glob_match(part, name))
        current = nxt
        if not current:
            return []
        if index < len(parts) - 1:
            current = [path for path in current if not _GLOB.search(part) or path in state.listings]
    return current


def _include_target(state: _State, path: str, source: str, depth: int, line: int) -> None:
    if path.rstrip('/') in state.listings:
        entries = state.listing(path)
        for name in entries or []:
            if name.startswith('.') or not _DIR_ENTRY.fullmatch(name):
                continue
            child = posixpath.join(path, name)
            if child in state.listings:
                state.gap('nested_directory', child, f'directory inside included directory {path}')
                continue
            _file(state, child, depth + 1, source)
        return
    _file(state, path, depth + 1, source)


def _include(state: _State, raw: str, source: str, depth: int, line: int) -> None:
    pattern = raw
    if pattern.startswith('/'):
        candidates = [pattern]
    else:
        candidates = [posixpath.join(base, pattern) for base in state.include_path]
    if _GLOB.search(pattern):
        found: list[tuple[str, list[str]]] = []
        for candidate in candidates:
            paths = _glob_paths(state, candidate, f'{source}:{line}')
            if paths is None:
                return
            if paths:
                found.append((candidate, paths))
        if len(found) > 1:
            state.gap('relative_glob_ambiguous', source, f'{pattern!r} matches under more than one include directory')
            return
        for path in found[0][1] if found else []:
            _include_target(state, path, source, depth, line)
        return
    for candidate in candidates:
        if state.has_file(candidate) or candidate.rstrip('/') in state.listings:
            _include_target(state, candidate, source, depth, line)
            return
        parent, name = posixpath.split(candidate.rstrip('/'))
        entries = state.listing(parent)
        if entries is None or name in entries:
            state.gap('file_not_observed', candidate, f'@include {pattern!r} at {source}:{line}')
            return
    state.stop('include_not_found', source, line, f'@include {pattern!r} does not exist')


def _pragma(state: _State, text: str, path: str, line: int, depth: int) -> None:
    word = text.split(None, 1)[0].rstrip(':')
    rest = text[len(text.split(None, 1)[0]):].strip()
    if word == '@include':
        target, unresolved = _expand_backticks(state, _pragma_value(rest))
        if unresolved:
            state.gap('backtick_unresolved', path, f'line {line}: @include uses {", ".join(unresolved)}')
            return
        _include(state, target, path, depth, line)
    elif word == '@define':
        match = _DEFINE.match(text)
        if not match:
            raise _Syntax(f'{path}:{line}: malformed @define')
        name, value = match.group(1), _pragma_value(match.group(2))
        state.defines[name] = value
        if name == 'allow-config-dups' and value.strip() not in ('', '0'):
            state.gap('allow_config_dups', path, 'Duplicate definitions are allowed; which one wins is not modelled.')
    elif word == '@module':
        _module(state, rest, path, line)


def _module(state: _State, rest: str, path: str, line: int) -> None:
    name = rest.split(None, 1)[0] if rest else ''
    if name != 'confgen':
        if name in ('mod-python', 'python', 'mod-java', 'java'):
            state.notes.append(f'{path}:{line} loads the {name} module; its code is not observed.')
        return
    options: dict[str, tuple[str, tuple[str, ...]]] = {}
    for match in re.finditer(r'([A-Za-z_-]+)\(\s*("(?:[^"\\]|\\.)*"|\'[^\']*\'|[^)\s]*)\s*\)', rest):
        raw = match.group(2)
        if raw[:1] == '"':
            value = decode_double(raw[1:-1])
        elif raw[:1] == "'":
            value = raw[1:-1]
        else:
            value = raw
        options[_norm(match.group(1))] = _expand_backticks(state, value)
    if not {'context', 'name', 'exec'} <= set(options):
        raise _Syntax(f'{path}:{line}: confgen needs context(), name() and exec()')
    command, unresolved = options['exec']
    state.confgen.append({'context': options['context'][0], 'name': _norm(options['name'][0]),
                          'command': command, 'unresolved': unresolved, 'path': path, 'line': line})


def _tokenize(state: _State, text: str, path: str, depth: int) -> None:
    index = 0
    line = 1
    at_line_start = True
    length = len(text)
    while index < length:
        char = text[index]
        if char == '\n':
            line += 1
            index += 1
            at_line_start = True
            continue
        if char in ' \t\r':
            index += 1
            continue
        if char == '#':
            end = text.find('\n', index)
            index = length if end < 0 else end
            continue
        if char == '@' and at_line_start:
            end = text.find('\n', index)
            end = length if end < 0 else end
            _pragma(state, text[index:end].rstrip('\r'), path, line, depth)
            index = end
            continue
        at_line_start = False
        if char in '"\'':
            start_line = line
            end = index + 1
            while True:
                if end >= length:
                    raise _Syntax(f'{path}:{start_line}: unterminated string')
                if char == '"' and text[end] == '\\':
                    end += 2
                    continue
                if text[end] == char:
                    break
                end += 1
            body = text[index + 1:end]
            line += body.count('\n')
            value = decode_double(body) if char == '"' else body
            value, unresolved = _expand_backticks(state, value)
            state.tokens.append(_Token('string', value, path, start_line, unresolved))
            index = end + 1
            continue
        if char in '{}();':
            state.tokens.append(_Token(char, char, path, line))
            index += 1
            continue
        if char == '`':
            end = text.find('`', index + 1)
            if end < 0:
                raise _Syntax(f'{path}:{line}: unterminated backtick')
            name = text[index + 1:end]
            if name not in state.defines:
                state.gap('backtick_unresolved', path, f'line {line}: `{name}` outside a string is not resolved')
            state.tokens.append(_Token('word', state.defines.get(name, ''), path, line, (name,)))
            index = end + 1
            continue
        match = _WORD.match(text, index)
        if not match:
            state.tokens.append(_Token('other', char, path, line))
            index += 1
            continue
        state.tokens.append(_Token('word', match.group(0), path, line))
        index = match.end()


def _file(state: _State, path: str, depth: int, included_from: str | None) -> None:
    if depth > MAX_DEPTH:
        state.gap('include_depth', path, f'included from {included_from}')
        return
    if len(state.read) >= MAX_FILES:
        state.gap('files_over_limit', path)
        return
    raw = state.files.get(path)
    record: dict[str, Any] = {'path': path, 'included_from': included_from, 'status': 'read'}
    state.read.append(record)
    if raw is None:
        record['status'] = 'not_observed'
        state.gap('file_not_observed', path, f'included from {included_from}' if included_from else '')
        return
    if isinstance(raw, bytes):
        try:
            raw = raw.decode('utf-8')
        except UnicodeDecodeError:
            record['status'] = 'invalid'
            state.gap('invalid_utf8', path)
            return
    if '\0' in raw:
        record['status'] = 'invalid'
        state.gap('binary', path)
        return
    if len(raw.encode('utf-8', 'surrogatepass')) > MAX_TEXT:
        record['status'] = 'invalid'
        state.gap('over_limit', path)
        return
    record['sha256'] = hashlib.sha256(raw.encode('utf-8', 'surrogatepass')).hexdigest()
    try:
        _tokenize(state, raw, path, depth)
    except _Syntax as exc:
        record['status'] = 'syntax_error'
        state.gap('syntax', path, str(exc))


# --- statement parser -------------------------------------------------------------------------------------

def _balanced(tokens: list[_Token], index: int, open_: str, close: str) -> int:
    """Return the index just past the token closing the group opened at ``index``."""
    depth = 0
    while index < len(tokens):
        kind = tokens[index].kind
        if kind == open_:
            depth += 1
        elif kind == close:
            depth -= 1
            if depth == 0:
                return index + 1
        index += 1
    raise _Syntax(f'unbalanced {open_}{close} opened at {tokens[-1].path if tokens else "?"}')


def _hooks(tokens: list[_Token]) -> list[tuple[str, _Token]]:
    found: list[tuple[str, _Token]] = []
    index = 0
    while index < len(tokens):
        token = tokens[index]
        if token.kind == 'word' and _norm(token.value) == 'hook-commands' and index + 1 < len(tokens) \
                and tokens[index + 1].kind == '(':
            end = _balanced(tokens, index + 1, '(', ')')
            inner = tokens[index + 2:end - 1]
            for position in range(len(inner) - 2):
                name = inner[position]
                if name.kind == 'word' and inner[position + 1].kind == '(' \
                        and inner[position + 2].kind == 'string' and _norm(name.value) in HOOKS:
                    found.append((_norm(name.value), inner[position + 2]))
            index = end
            continue
        index += 1
    return found


def _drivers(tokens: list[_Token]) -> list[tuple[_Token, list[_Token]]]:
    """Split a source/destination body into (driver name, argument tokens)."""
    drivers: list[tuple[_Token, list[_Token]]] = []
    index = 0
    while index < len(tokens):
        token = tokens[index]
        if token.kind == ';':
            index += 1
            continue
        if token.kind not in ('word', 'string') or index + 1 >= len(tokens) or tokens[index + 1].kind != '(':
            raise _Syntax(f'{token.path}:{token.line}: expected a driver, found {token.value!r}')
        end = _balanced(tokens, index + 1, '(', ')')
        drivers.append((token, tokens[index + 2:end - 1]))
        index = end
    return drivers


class _Object:
    def __init__(self, context: str, name: str | None, token: _Token, body: list[_Token]):
        self.context = context
        self.name = name
        self.token = token
        self.body = body
        self.referenced = name is None


def _references(state: _State, tokens: list[_Token], objects: list[_Object],
                refs: list[tuple[str, str, _Token]]) -> None:
    index = 0
    while index < len(tokens):
        token = tokens[index]
        nxt = tokens[index + 1] if index + 1 < len(tokens) else None
        if token.kind == 'word' and _norm(token.value) in ('source', 'destination') and nxt is not None:
            context = _norm(token.value)
            if nxt.kind == '(':
                end = _balanced(tokens, index + 1, '(', ')')
                inner = tokens[index + 2:end - 1]
                if len(inner) != 1 or inner[0].kind not in ('word', 'string'):
                    raise _Syntax(f'{token.path}:{token.line}: malformed {context}() reference')
                refs.append((context, inner[0].value, token))
                index = end
                continue
            if nxt.kind == '{':
                end = _balanced(tokens, index + 1, '{', '}')
                objects.append(_Object(context, None, token, tokens[index + 2:end - 1]))
                index = end
                continue
        index += 1


def _parse(state: _State) -> tuple[list[_Object], list[tuple[str, str, _Token]], dict[str, set[str]]]:
    tokens = state.tokens
    objects: list[_Object] = []
    refs: list[tuple[str, str, _Token]] = []
    blocks: dict[str, set[str]] = {}
    index = 0
    while index < len(tokens):
        token = tokens[index]
        if token.kind == ';':
            index += 1
            continue
        if token.kind != 'word':
            raise _Syntax(f'{token.path}:{token.line}: unexpected {token.value!r}')
        keyword = _norm(token.value)
        brace = index + 1
        while brace < len(tokens) and tokens[brace].kind not in ('{', ';'):
            brace += 1
        if brace >= len(tokens) or tokens[brace].kind != '{':
            raise _Syntax(f'{token.path}:{token.line}: statement {token.value!r} has no body')
        end = _balanced(tokens, brace, '{', '}')
        header = tokens[index + 1:brace]
        body = tokens[brace + 1:end - 1]
        if keyword in ('source', 'destination'):
            if len(header) != 1 or header[0].kind not in ('word', 'string'):
                raise _Syntax(f'{token.path}:{token.line}: malformed {keyword} name')
            objects.append(_Object(keyword, header[0].value, token, body))
        elif keyword == 'log':
            _references(state, body, objects, refs)
        elif keyword == 'block':
            if len(header) >= 2 and header[1].kind == 'word':
                blocks.setdefault(_norm(header[0].value), set()).add(_norm(header[1].value))
        index = end
    return objects, refs, blocks


def _entry(kind: str, context: str, object_name: str | None, driver: str, token: _Token, argv: tuple[str, ...],
           timing: str, **extra: Any) -> dict[str, Any]:
    return {
        'kind': kind,
        'context': context,
        'object': object_name,
        'driver': driver,
        'command': token.value,
        'argv': [*argv, token.value],
        'path': token.path,
        'line': token.line,
        'when': timing,
        'unresolved_backticks': list(token.unresolved),
        **extra,
    }


def _commands(state: _State, objects: list[_Object], blocks: dict[str, set[str]]) -> list[dict[str, Any]]:
    commands: list[dict[str, Any]] = []
    confgen = {(item['context'], item['name']): item for item in state.confgen}
    for obj in objects:
        try:
            drivers = _drivers(obj.body)
        except _Syntax as exc:
            state.gap('syntax', obj.token.path, str(exc))
            continue
        for name_token, args in drivers:
            driver = _norm(name_token.value)
            status = 'runs' if obj.referenced else 'not_referenced'
            if driver == 'program':
                if not args or args[0].kind != 'string':
                    state.gap('syntax', name_token.path, f'line {name_token.line}: program() needs a command string')
                    continue
                if len(args) > 1 and args[1].kind == 'string':
                    state.stop('syntax', name_token.path, name_token.line,
                               'program() has two adjacent strings; syslog-ng rejects the configuration')
                timing = ('while syslog-ng runs; restarted when it exits' if obj.context == 'source'
                          else 'while syslog-ng runs; receives each routed message on stdin')
                commands.append(_entry(f'program_{obj.context}', obj.context, obj.name, driver, args[0],
                                       PROGRAM_ARGV, timing, status=status))
            elif (obj.context, driver) in confgen:
                item = confgen[(obj.context, driver)]
                token = _Token('string', item['command'], item['path'], item['line'], item['unresolved'])
                commands.append(_entry('confgen', obj.context, obj.name, driver, token, HOOK_ARGV,
                                       'when syslog-ng loads its configuration', status=status,
                                       used_at={'path': name_token.path, 'line': name_token.line}))
                if obj.referenced:
                    state.gap('confgen_output', item['path'],
                              f'{driver}() generates configuration at load time; its output is not observed')
            elif driver in blocks.get(obj.context, set()):
                if obj.referenced:
                    state.gap('block_driver', name_token.path,
                              f'line {name_token.line}: {driver}() is a block; its body is not expanded')
            for hook, token in _hooks(args):
                commands.append(_entry('hook', obj.context, obj.name, driver, token, HOOK_ARGV,
                                       HOOK_TIMING[hook], status=status, hook=hook))
    return commands


def resolve(files: Mapping[str, str | bytes | None], listings: Mapping[str, Iterable[str] | None] | None = None,
            config: str = DEFAULT_CONFIG,
            include_path: Iterable[str] = DEFAULT_INCLUDE_PATH) -> dict[str, Any]:
    """Resolve the commands syslog-ng runs from captured configuration.

    ``files`` maps absolute paths to captured text; ``None`` or a missing key
    means the file was not observed. ``listings`` maps observed directories to
    their entry names; a listed directory is how an include target's absence
    is confirmed, and a path that is itself a listed directory is a directory
    include.
    """
    state = _State(files, listings or {}, tuple(path.rstrip('/') for path in include_path))
    _file(state, config, 0, None)
    objects: list[_Object] = []
    commands: list[dict[str, Any]] = []
    if not any(gap['code'] == 'syntax' for gap in state.gaps):
        try:
            objects, refs, blocks = _parse(state)
        except _Syntax as exc:
            state.gap('syntax', None, str(exc))
            refs, blocks = [], {}
        named: dict[tuple[str, str], _Object] = {}
        dups_allowed = state.defines.get('allow-config-dups', '0').strip() not in ('', '0')
        for obj in objects:
            if obj.name is None:
                continue
            key = (obj.context, obj.name)
            if key in named and not dups_allowed:
                state.stop('duplicate_definition', obj.token.path, obj.token.line,
                           f'duplicate {obj.context} {obj.name!r}')
            named[key] = obj
        for context, name, token in refs:
            target = named.get((context, name))
            if target is None:
                state.stop('unresolved_reference', token.path, token.line,
                           f'log path references undefined {context} {name!r}')
            else:
                target.referenced = True
        commands = _commands(state, objects, blocks)
    if len(commands) > MAX_COMMANDS:
        state.gap('commands_over_limit', None, f'{len(commands)} commands')
        commands = commands[:MAX_COMMANDS]
    for command in commands:
        if state.fatal and command['status'] == 'runs':
            command['status'] = 'rejected'
        if command['status'] == 'runs' and command['unresolved_backticks']:
            command['status'] = 'unresolved'
            state.gap('backtick_unresolved', command['path'],
                      f'line {command["line"]}: {", ".join(command["unresolved_backticks"])} not resolved')
    complete = not any(gap['blocking'] for gap in state.gaps)
    for command in commands:
        if command['status'] == 'runs':
            command['complete'] = complete
            command['runs_as'] = {'user': 'root', 'source': 'package_default',
                                  'detail': 'syslog-ng runs as root unless its command line passes --user.'}
    return {
        'contract_version': CONTRACT_VERSION,
        'source_versions': list(SOURCE_VERSIONS),
        'config': config,
        'include_path': list(state.include_path),
        'complete': complete,
        'starts': not state.fatal,
        'fatal': state.fatal,
        'commands': commands,
        'running': [command for command in commands if command['status'] == 'runs'],
        'files': state.read,
        'gaps': state.gaps,
        'notes': state.notes,
        'not_observed': list(NOT_OBSERVED),
        'origin': 'not_assessed',
        'authorizes_response': False,
    }
